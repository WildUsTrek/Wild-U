window.getPlayerRankInfo = function getPlayerRankInfo(progress) {
  const p = progress || (typeof getCurrentProgress === 'function' ? getCurrentProgress() : {});
  const highestSkill = Math.max(0, Math.min(9, Number(p.highestSkillBeaten) || 0));
  const rank = highestSkill > 0 ? Math.max(1, Math.min(10, 10 - highestSkill)) : 10;
  return {
    rank,
    total: 10,
    highestSkill,
    label: `grado #${rank}`,
    fullLabel: `grado #${rank}/10`
  };
};

window.getOpponentRankInfo = function getOpponentRankInfo(opponent, progress) {
  const skill = Math.max(1, Math.min(9, Number(opponent && opponent.skill) || 1));
  const p = progress || (typeof getCurrentProgress === 'function' ? getCurrentProgress() : {});
  const highestSkill = Math.max(0, Math.min(9, Number(p.highestSkillBeaten) || 0));
  const beaten = highestSkill >= skill;
  // 9 sfidanti + TU: quando TU supera uno sfidante, quello scende sotto di lui.
  const rank = beaten ? Math.max(2, Math.min(10, 11 - skill)) : Math.max(1, Math.min(9, 10 - skill));
  return {
    rank,
    total: 10,
    skill,
    beaten,
    label: `grado #${rank}`,
    fullLabel: `grado #${rank}/10`,
    relation: beaten ? 'sotto di te' : 'sopra di te'
  };
};

