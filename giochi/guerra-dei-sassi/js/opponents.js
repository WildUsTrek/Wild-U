window.tabula = async function tabula(force) {
  const ok = force === true || force === 'yes' || force === 'si' || force === 'sì' || (
    typeof window.confirm === 'function'
      ? window.confirm('Azzerare progressi e preferenze audio di Sfida dei Sassi?')
      : true
  );
  if (!ok) return 'stone-war tabula: annullato';

  const ownedKeys = window.STONE_WAR_OWNED_STORAGE_KEYS;
  const removed = { localStorage: 0, sessionStorage: 0 };

  try {
    if (window.localStorage) {
      ownedKeys.forEach((key) => {
        if (window.localStorage.getItem(key) !== null) {
          window.localStorage.removeItem(key);
          removed.localStorage += 1;
        }
      });
    }
  } catch (err) {}

  try {
    if (window.sessionStorage) {
      ownedKeys.forEach((key) => {
        if (window.sessionStorage.getItem(key) !== null) {
          window.sessionStorage.removeItem(key);
          removed.sessionStorage += 1;
        }
      });
    }
  } catch (err) {}

  try {
    window.__stoneWarAdminUnlockAll = false;
    if (window.GameState) {
      GameState.adminUnlockAllChallenges = false;
      GameState.progress = null;
    }
  } catch (err) {}

  try {
    if (typeof window.returnToMenu === 'function') window.returnToMenu();
    window.dispatchEvent(new CustomEvent('stone-war:owned-storage-reset', { detail: Object.assign({}, removed) }));
  } catch (err) {}

  console.info('[stone-war tabula] storage posseduto azzerato', removed);
  return `stone-war tabula: localStorage ${removed.localStorage}, sessionStorage ${removed.sessionStorage}`;
};


