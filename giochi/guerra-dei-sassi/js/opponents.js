window.isOpponentChallengeUnlocked = function isOpponentChallengeUnlocked(opponent, progress) {
  if (!opponent) return false;
  if (typeof isAdminChallengeUnlockActive === 'function' && isAdminChallengeUnlockActive()) return true;
  const p = progress || (typeof getCurrentProgress === 'function' ? getCurrentProgress() : {});
  const highestSkill = Math.max(0, Math.min(9, Number(p.highestSkillBeaten) || 0));
  const skill = Math.max(1, Math.min(9, Number(opponent.skill) || 1));
  return skill === 1 || highestSkill >= (skill - 1);
};

